// Writes the cases V8's date parser reads, as a Rust file the gantt tests read.
//
//   node tools/oracle/dates.mjs
//
// The reference is V8 itself: `new Date(text)` in Node, with the zone pinned to UTC, since
// fermaid reads and draws dates in UTC.
process.env.TZ = 'UTC';

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const target = join(root, 'crates/fermaid/src/diagrams/gantt/date_cases.rs');

// The forms the parser has to read, and the ones it has to refuse.
const seeds = [
  // The date time string format.
  '2020-01-05', '2020-01-05T10:00', '2020-01-05T10:00:00', '2020-01-05T10:00:00.500Z',
  '2020-01-05T10:00:00+02:00', '2020-01-05T10:00:00-0500', '2020-01-05T10:00:00+0200',
  '2020-01-05T24:00', '2020-01-05T24:00:00', '0000-01-05', '9999-12-31', '-000001',
  '+002020-01-05', '1970-01-01', '1969-12-31',
  // Dates the format does not match.
  '2014-1-12', '2020-1-5', '2024-01-001', '2014-001', '2-01-12', '201-01-01',
  '2020-01-05 10:00', '2020-01-05T10:00:00.5Z', '2020-01-05T10:00:00.123456Z',
  // Month names.
  'Jan 5 2020', '5 Jan 2020', 'March 5, 2020', 'Dec 25', 'Jan 5', 'Mar 2020', '2020 Jan 5',
  '5 Jan', 'Jan 5, 2020 10:00:00', 'jan 5 2020', 'JAN 5 2020', 'Jan-05-2020', '2020-Jan-05',
  // Numbers on their own.
  '0', '5', '12', '49', '99', '2014', '2020', '20200105', '7:30', '12:00:00', '1 17:30',
  // Times.
  'Jan 5 2020 10:00 pm', 'Jan 5 2020 10:00 am', '1 17:30', '2020-01-05 12:00:00.123',
  '2020-01-05T10:00:00.1', '17:30',
  // Time zones.
  '2020-01-05 GMT', '1 Jan 2020 GMT+0300', 'Jan 5 2020 GMT', 'Mon, 05 Jan 2020 10:00:00 GMT',
  'Tue, 05 Jan 2020 10:00:00 EST', '2020-01-05T10:00:00Z', '2020-01-05T10:00:00+02',
  '2020-01-05 GMT+3', '2020-01-05 GMT-8',
  // Words, brackets and other text.
  'done 2014-01-06', 'accDescr { d } 0', 'a 2014-01-01', 'crit 2014-01-06', '2020-01-05 (comment)',
  '(2020-01-05)', 'vert 2014-01-01', 'weekday monday 2024-01-01', '1%%7:58',
  'ntt 2017-07-20', '<script>alert(1)</script> 2024-10-01',
  // What the parser refuses.
  '2020-13-05', '2020-00-01', '2020-01-00', '2020-01-32', '2023-02-29', 'May', '',
  'not a date', '2020-01-05T', 'T10:00', '2020-01-05T10:00:00.5',
];

const tokens = [
  'gantt', 'dateFormat', 'accDescr', '{', '}', '0', '5', '12', '49', '2014', '2020',
  'Jan', 'jan', 'February', 'Dec', 'am', 'pm', 'GMT', 'UTC', 'Z', 'T', '-', '+', ':',
  '.', '/', ',', ' ', '(', ')', 'x', 'done', 'crit', 'milestone', '%', '#', ';', 'é',
  '17:30', '10:00', '2020-01-05', '2020-1-5', '2024-01-001', '24:00', '12:60', '99:99',
  '\t', '\n', '\u2028', '\u0000',
];

// A fixed seed, so that a run can be repeated.
let state = 20200105;
const rnd = (n) => {
  state = (state * 1103515245 + 12345) & 0x7fffffff;
  return state % n;
};

const texts = new Set(seeds);
for (const seed of seeds) {
  for (let i = 0; i < 6; i++) {
    const at = rnd(seed.length + 1);
    const kind = rnd(4);
    let text;
    if (kind === 0) text = seed.slice(0, at) + seed.slice(at + 1);
    else if (kind === 1) text = seed.slice(0, at) + tokens[rnd(tokens.length)] + seed.slice(at);
    else if (kind === 2) text = seed.slice(0, at) + String(rnd(1000)) + seed.slice(at);
    else text = seed.slice(0, at) + tokens[rnd(tokens.length)] + seed.slice(at + 1);
    texts.add(text);
  }
}
for (let i = 0; i < 400; i++) {
  const parts = [];
  const count = 1 + rnd(5);
  for (let j = 0; j < count; j++) parts.push(tokens[rnd(tokens.length)]);
  texts.add(parts.join(rnd(2) === 0 ? ' ' : ''));
}

const cases = [...texts].map((text) => {
  const time = new Date(text).getTime();
  return [text, Number.isNaN(time) ? null : time];
});

const escape = (text) =>
  Array.from(text)
    .map((c) => {
      const code = c.codePointAt(0);
      if (code < 0x20 || code === 0x7f) return `\\u{${code.toString(16)}}`;
      if (code > 0x7e) return `\\u{${code.toString(16)}}`;
      return c;
    })
    .join('');

const body = cases
  .map(([text, time]) => `    ("${escape(text)}", ${time === null ? 'None' : `Some(${time}.0)`}),`)
  .join('\n');

writeFileSync(
  target,
  `//! What V8's date parser makes of the cases in \`tools/oracle/dates.mjs\`. The time is in
//! milliseconds since the epoch, and \`None\` is a date V8 refuses.
//!
//! Generated by \`node tools/oracle/dates.mjs\`; do not edit by hand.

pub(crate) const CASES: &[(&str, Option<f64>)] = &[
${body}
];
`,
);

// rustfmt lays the file out, so that a regenerated file is the file that was committed.
try {
  execFileSync('rustfmt', ['--edition', '2024', target], { stdio: 'inherit' });
} catch {
  console.log('rustfmt was not found; run cargo fmt on the file');
}

console.log(`wrote ${cases.length} cases to ${target}`);
