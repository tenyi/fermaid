//! Development tasks. `cargo xtask compat <TYPE> --pele <DIR>` reads the Mermaid spec cases that
//! pele ports into `tests/compat/<TYPE>` and writes them out as Rust test data, in
//! `crates/fermaid/tests/compat/<TYPE>/cases.rs`.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

const USAGE: &str = "\
Usage: cargo xtask compat <TYPE> --pele <DIR>

Converts pele's ported Mermaid spec cases for TYPE (a folder name in pele's tests/compat,
such as pie) into crates/fermaid/tests/compat/TYPE/cases.rs.";

fn main() -> ExitCode {
    match run(std::env::args().skip(1).collect()) {
        Ok(message) => {
            println!("{message}");
            ExitCode::SUCCESS
        }
        Err(message) => {
            eprintln!("xtask: {message}");
            ExitCode::FAILURE
        }
    }
}

fn run(args: Vec<String>) -> Result<String, String> {
    let mut args = args.into_iter();
    let mut kind = None;
    let mut pele = None;
    let command = args.next().ok_or(USAGE)?;
    if command != "compat" {
        return Err(format!("unknown command: {command}\n\n{USAGE}"));
    }
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--pele" => pele = Some(PathBuf::from(args.next().ok_or("--pele needs a value")?)),
            "-h" | "--help" => return Ok(USAGE.to_string()),
            _ if kind.is_none() => kind = Some(arg),
            _ => return Err(format!("unexpected argument: {arg}\n\n{USAGE}")),
        }
    }
    let kind = kind.ok_or(USAGE)?;
    let pele = pele.ok_or(USAGE)?;
    compat(&kind, &pele)
}

fn compat(kind: &str, pele: &Path) -> Result<String, String> {
    if !kind.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') {
        return Err(format!("invalid type: {kind}"));
    }
    let dir = pele.join("tests/compat").join(kind);
    let mut files: Vec<PathBuf> = std::fs::read_dir(&dir)
        .map_err(|e| format!("{}: {e}", dir.display()))?
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| {
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
            [".spec.ts", ".test.ts", ".spec.js", ".test.js"]
                .iter()
                .any(|s| name.ends_with(s))
        })
        .collect();
    files.sort();
    if files.is_empty() {
        return Err(format!("no spec files in {}", dir.display()));
    }
    let version = pele_version(pele);
    let mut out = format!(
        "// Mermaid spec cases for {kind}, as ported by pele {version} in tests/compat/{kind}.\n\
         // Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.\n\
         // Generated by `cargo xtask compat {kind}`; do not edit.\n\n\
         const CASES: &[Case] = &[\n"
    );
    let mut count = 0;
    for path in &files {
        let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
        let file = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
        let cases = extract(&text).map_err(|e| format!("{}: {e}", path.display()))?;
        for case in cases {
            let _ = writeln!(
                out,
                "    Case {{\n        file: {file:?},\n        name: {:?},\n        src: {:?},\n        todo: {},\n    }},",
                case.name, case.src, case.todo
            );
            count += 1;
        }
    }
    out.push_str("];\n");
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("no workspace root")?;
    let target = root.join("crates/fermaid/tests/compat").join(kind);
    std::fs::create_dir_all(&target).map_err(|e| format!("{}: {e}", target.display()))?;
    let target = target.join("cases.rs");
    std::fs::write(&target, out).map_err(|e| format!("{}: {e}", target.display()))?;
    Ok(format!("wrote {count} cases to {}", target.display()))
}

fn pele_version(pele: &Path) -> String {
    let manifest = std::fs::read_to_string(pele.join("package.json")).unwrap_or_default();
    manifest
        .lines()
        .find_map(|line| {
            let rest = line.trim().strip_prefix("\"version\":")?;
            Some(
                rest.trim()
                    .trim_end_matches(',')
                    .trim_matches('"')
                    .to_string(),
            )
        })
        .unwrap_or_else(|| "(unknown version)".to_string())
}

#[derive(Debug, Clone, PartialEq)]
enum Tok {
    Ident(String),
    Punct(char),
    /// A string or template literal, cooked. A template with `${}` holes keeps them as written.
    Str(String),
}

#[derive(Debug, PartialEq)]
struct Case {
    name: String,
    src: String,
    todo: bool,
}

/// Splits TypeScript into the tokens the extractor needs, skipping comments and regex literals.
fn tokenize(text: &str) -> Result<Vec<Tok>, String> {
    let chars: Vec<char> = text.chars().collect();
    let mut toks = Vec::new();
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        if c.is_whitespace() {
            i += 1;
        } else if c == '/' && chars.get(i + 1) == Some(&'/') {
            while i < chars.len() && chars[i] != '\n' {
                i += 1;
            }
        } else if c == '/' && chars.get(i + 1) == Some(&'*') {
            i += 2;
            while i < chars.len() && !(chars[i] == '*' && chars.get(i + 1) == Some(&'/')) {
                i += 1;
            }
            i += 2;
        } else if c == '/' && regex_allowed(toks.last()) {
            i = skip_regex(&chars, i)?;
        } else if c == '"' || c == '\'' || c == '`' {
            let (value, end) = literal(&chars, i)?;
            toks.push(Tok::Str(value));
            i = end;
        } else if c.is_alphanumeric() || c == '_' || c == '$' {
            let start = i;
            while i < chars.len()
                && (chars[i].is_alphanumeric() || chars[i] == '_' || chars[i] == '$')
            {
                i += 1;
            }
            toks.push(Tok::Ident(chars[start..i].iter().collect()));
        } else {
            toks.push(Tok::Punct(c));
            i += 1;
        }
    }
    Ok(toks)
}

fn regex_allowed(prev: Option<&Tok>) -> bool {
    match prev {
        None => true,
        Some(Tok::Punct(c)) => "([{,;:=!&|?+-*%<>~^".contains(*c),
        Some(Tok::Ident(word)) => matches!(word.as_str(), "return" | "typeof" | "case"),
        Some(Tok::Str(_)) => false,
    }
}

fn skip_regex(chars: &[char], mut i: usize) -> Result<usize, String> {
    i += 1;
    let mut class = false;
    while i < chars.len() {
        match chars[i] {
            '\\' => i += 1,
            '[' => class = true,
            ']' => class = false,
            '/' if !class => {
                i += 1;
                while i < chars.len() && chars[i].is_alphabetic() {
                    i += 1;
                }
                return Ok(i);
            }
            '\n' => return Err("unterminated regular expression".to_string()),
            _ => {}
        }
        i += 1;
    }
    Err("unterminated regular expression".to_string())
}

/// Reads a string or template literal at `start` and returns its cooked value.
fn literal(chars: &[char], start: usize) -> Result<(String, usize), String> {
    let quote = chars[start];
    let mut out = String::new();
    let mut i = start + 1;
    while i < chars.len() {
        let c = chars[i];
        if c == quote {
            return Ok((out, i + 1));
        }
        if quote == '`' && c == '$' && chars.get(i + 1) == Some(&'{') {
            // Kept as written: the cases that need a value from the test code are skipped.
            let mut depth = 0;
            while i < chars.len() {
                out.push(chars[i]);
                match chars[i] {
                    '{' => depth += 1,
                    '}' => {
                        depth -= 1;
                        if depth == 0 {
                            break;
                        }
                    }
                    _ => {}
                }
                i += 1;
            }
            i += 1;
            continue;
        }
        if c != '\\' {
            out.push(c);
            i += 1;
            continue;
        }
        let next = *chars.get(i + 1).ok_or("unterminated escape")?;
        i += 2;
        match next {
            'n' => out.push('\n'),
            't' => out.push('\t'),
            'r' => out.push('\r'),
            'b' => out.push('\u{8}'),
            'f' => out.push('\u{c}'),
            'v' => out.push('\u{b}'),
            '0' => out.push('\0'),
            '\n' => {}
            'x' => {
                let hex: String = chars[i..(i + 2).min(chars.len())].iter().collect();
                out.push(code_point(&hex)?);
                i += 2;
            }
            'u' if chars.get(i) == Some(&'{') => {
                let end = (i..chars.len())
                    .find(|&j| chars[j] == '}')
                    .ok_or("unterminated escape")?;
                let hex: String = chars[i + 1..end].iter().collect();
                out.push(code_point(&hex)?);
                i = end + 1;
            }
            'u' => {
                let hex: String = chars[i..(i + 4).min(chars.len())].iter().collect();
                out.push(code_point(&hex)?);
                i += 4;
            }
            c => out.push(c),
        }
    }
    Err("unterminated string".to_string())
}

fn code_point(hex: &str) -> Result<char, String> {
    u32::from_str_radix(hex, 16)
        .ok()
        .and_then(char::from_u32)
        .ok_or_else(|| format!("invalid escape: {hex}"))
}

fn is_punct(tok: Option<&Tok>, c: char) -> bool {
    tok == Some(&Tok::Punct(c))
}

/// The index just past the bracket that closes the one at `open`.
fn closing(toks: &[Tok], open: usize) -> Result<usize, String> {
    let mut depth = 0;
    for (i, tok) in toks.iter().enumerate().skip(open) {
        match tok {
            Tok::Punct('(' | '[' | '{') => depth += 1,
            Tok::Punct(')' | ']' | '}') => {
                depth -= 1;
                if depth == 0 {
                    return Ok(i + 1);
                }
            }
            _ => {}
        }
    }
    Err("unbalanced brackets".to_string())
}

fn first_string(toks: &[Tok]) -> Option<String> {
    toks.iter().find_map(|tok| match tok {
        Tok::Str(s) => Some(s.clone()),
        _ => None,
    })
}

/// Finds the `describe`/`it` structure of a spec file and the diagram source of each test: the
/// first string literal in its body, or each element of an `it.each` table.
fn extract(text: &str) -> Result<Vec<Case>, String> {
    let toks = tokenize(text)?;
    let mut cases = Vec::new();
    let mut scopes: Vec<(String, usize)> = Vec::new();
    let mut i = 0;
    while i < toks.len() {
        while scopes.last().is_some_and(|&(_, end)| i >= end) {
            scopes.pop();
        }
        let path = |name: &str, scopes: &[(String, usize)]| {
            let mut parts: Vec<&str> = scopes.iter().map(|(s, _)| s.as_str()).collect();
            parts.push(name);
            parts.join(" > ")
        };
        let Some(Tok::Ident(word)) = toks.get(i) else {
            i += 1;
            continue;
        };
        if is_punct(toks.get(i.wrapping_sub(1)), '.') {
            i += 1;
            continue;
        }
        let call = match word.as_str() {
            "describe" | "it" | "test" => i + 1,
            _ => {
                i += 1;
                continue;
            }
        };
        let modifier = match (toks.get(call), toks.get(call + 1)) {
            (Some(Tok::Punct('.')), Some(Tok::Ident(m))) => Some(m.as_str()),
            _ => None,
        };
        let open = if modifier.is_some() { call + 2 } else { call };
        if !is_punct(toks.get(open), '(') {
            i += 1;
            continue;
        }
        let end = closing(&toks, open)?;
        if word == "describe" {
            if let Some(Tok::Str(name)) = toks.get(open + 1) {
                scopes.push((name.clone(), end));
            }
            i = open + 1;
            continue;
        }
        match modifier {
            Some("each") => {
                // it.each([...])('name', fn)
                let table = &toks[open + 1..end - 1];
                let mut sources = Vec::new();
                if is_punct(table.first(), '[') {
                    let mut depth = 0;
                    for tok in table {
                        match tok {
                            Tok::Punct('(' | '[' | '{') => depth += 1,
                            Tok::Punct(')' | ']' | '}') => depth -= 1,
                            Tok::Str(s) if depth == 1 => sources.push(s.clone()),
                            _ => {}
                        }
                    }
                }
                let Some(Tok::Str(name)) =
                    toks.get(end + 1).filter(|_| is_punct(toks.get(end), '('))
                else {
                    return Err("it.each without a test name".to_string());
                };
                let body_end = closing(&toks, end)?;
                let name = path(name, &scopes);
                for (n, src) in sources.into_iter().enumerate() {
                    cases.push(Case {
                        name: format!("{name} [{n}]"),
                        src,
                        todo: false,
                    });
                }
                i = body_end;
            }
            None | Some("todo" | "skip" | "only") => {
                let Some(Tok::Str(name)) = toks.get(open + 1) else {
                    i = end;
                    continue;
                };
                cases.push(Case {
                    name: path(name, &scopes),
                    src: first_string(&toks[open + 2..end]).unwrap_or_default(),
                    todo: matches!(modifier, Some("todo" | "skip")),
                });
                i = end;
            }
            Some(_) => i = end,
        }
    }
    Ok(cases)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn extracts_cases() {
        let spec = r#"
            // a comment with `backticks`
            describe('pie', () => {
              beforeEach(() => db.clear());
              it('simple', async () => {
                await parser.parse(`pie
                  "a\t": 1`);
                expect(x).toMatch(/a"b/);
              });
              it.todo('later', () => {});
              describe('each', () => {
                it.each([`pie`, `\tpie`])('regular', (context: string) => {
                  parse(context);
                });
              });
            });
            it('outside', () => { const s = "pie\n"; });
        "#;
        let cases = extract(spec).unwrap();
        let names: Vec<&str> = cases.iter().map(|c| c.name.as_str()).collect();
        assert_eq!(
            names,
            [
                "pie > simple",
                "pie > later",
                "pie > each > regular [0]",
                "pie > each > regular [1]",
                "outside"
            ]
        );
        assert_eq!(cases[0].src, "pie\n                  \"a\t\": 1");
        assert!(cases[1].todo);
        assert_eq!(cases[1].src, "");
        assert_eq!(cases[3].src, "\tpie");
        assert_eq!(cases[4].src, "pie\n");
    }

    #[test]
    fn cooks_escapes() {
        let chars: Vec<char> = r"'\x41B\u{43}\'\\'".chars().collect();
        assert_eq!(literal(&chars, 0).unwrap().0, "ABC'\\");
    }
}
